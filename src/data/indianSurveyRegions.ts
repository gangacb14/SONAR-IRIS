interface TargetFactoryInput {
  id: string;
  surveyId: string;
  transectId: string;
  pingNumber: number;
  channel: ChannelType;
  classification: DebrisCategory;
  categoryLabel: string;
  confidence: number;
  latitude: number;
  longitude: number;
  depth: number;
  slantRange: number;
  towfishAltitude: number;
  estimatedLength: number;
  estimatedWidth: number;
  shadowLength: number;
  backscatter: number;
  severity: SeverityLevel;
  verificationStatus: VerificationStatus;
  detectedAt: string;
  operatorNotes: string;
  waterfallBox: { x: number; y: number; width: number; height: number };
  featureName: string;
}

function createRegionalTarget(input: TargetFactoryInput): Target {
  const utm = wgs84ToUtm(input.latitude, input.longitude);
  const shadowHeight = Math.round(((input.shadowLength * input.towfishAltitude) / input.slantRange) * 100) / 100;
  const groundRange = Math.round(Math.sqrt(Math.max(0, input.slantRange ** 2 - input.towfishAltitude ** 2)) * 10) / 10;

  return {
    id: input.id,
    surveyId: input.surveyId,
    transectId: input.transectId,
    pingNumber: input.pingNumber,
    channel: input.channel,
    classification: input.classification,
    categoryLabel: input.categoryLabel,
    confidence: input.confidence,
    latitude: input.latitude,
    longitude: input.longitude,
    coordinateReferenceSystem: 'WGS84 / UTM Geographic [DEMO / SIMULATED GEOREFERENCING]',
    utmZone: utm.zone,
    utmEasting: utm.easting,
    utmNorthing: utm.northing,
    depth: input.depth,
    slantRange: input.slantRange,
    groundRange,
    towfishAltitude: input.towfishAltitude,
    estimatedLength: input.estimatedLength,
    estimatedWidth: input.estimatedWidth,
    shadowLength: input.shadowLength,
    shadowHeight,
    backscatter: input.backscatter,
    severity: input.severity,
    verificationStatus: input.verificationStatus,
    operatorNotes: input.operatorNotes,
    detectedAt: input.detectedAt,
    sonarEvidenceReference: {
      waterfallBox: input.waterfallBox,
      rangeMeters: input.slantRange,
      pingOffset: input.pingNumber,
    },
    modelMetadata: {
      modelName: 'SONAR-IRIS Sonar-CNN v2.6',
      featureExtractor: input.featureName,
      snrDb: 22.0 + Math.round(input.confidence * 100) / 10,
      shadowContrastRatio: 4.5 + Math.round(input.confidence * 40) / 10,
    },
    // Legacy support fields
    transectLine: input.transectId,
    category: input.classification,
    timestamp: input.detectedAt,
    slantRangeMeters: input.slantRange,
    groundRangeMeters: groundRange,
    towfishAltitudeMeters: input.towfishAltitude,
    shadowLengthMeters: input.shadowLength,
    estimatedTargetHeightMeters: shadowHeight,
    estimatedLengthMeters: input.estimatedLength,
    estimatedWidthMeters: input.estimatedWidth,
    backscatterDb: input.backscatter,
    coordinates: {
      lat: input.latitude,
      lng: input.longitude,
      utmZone: utm.zone,
      utmEasting: utm.easting,
      utmNorthing: utm.northing,
      depthMeters: input.depth,
    },
    waterfallBox: input.waterfallBox,
  };
}

